const originals = new WeakMap();

function translateText(value) {
  if (!value || !value.trim()) return value;
  const trimmed = value.trim();
  if (HI[trimmed]) return value.replace(trimmed, HI[trimmed]);
  let result = value;
  Object.entries(HI).sort((a, b) => b[0].length - a[0].length).forEach(([en, hi]) => {
    result = result.split(en).join(hi);
  });
  Object.entries(WORDS).forEach(([en, hi]) => {
    result = result.replace(new RegExp(`\\b${en}\\b`, "g"), hi);
  });
  return result;
}

export function translatePage(language) {
  const root = document.body;
  if (!root) return;
  if (language !== "hi") {
    document.querySelectorAll("[data-roadsense-original]").forEach((el) => {
      const original = el.getAttribute("data-roadsense-original");
      if (original !== null) {
        if (el.nodeType === Node.ELEMENT_NODE) el.textContent = original;
        el.removeAttribute("data-roadsense-original");
      }
    });
    originals.forEach?.(() => {});
    return;
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let node;
  while ((node = walker.nextNode())) {
    if (!node.parentElement || /^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA)$/.test(node.parentElement.tagName)) continue;
    nodes.push(node);
  }
  nodes.forEach((textNode) => {
    if (!originals.has(textNode)) originals.set(textNode, textNode.nodeValue);
    textNode.nodeValue = translateText(originals.get(textNode));
  });
  document.querySelectorAll("[aria-label], [title], input[placeholder]").forEach((el) => {
    ["aria-label", "title", "placeholder"].forEach((attr) => {
      if (!el.hasAttribute(attr)) return;
      const key = `${attr}:${el}`;
      const current = el.getAttribute(attr);
      if (!el.dataset[`roadsense${attr.replace(/[^a-z]/gi, "")}`]) el.dataset[`roadsense${attr.replace(/[^a-z]/gi, "")}`] = current;
      const original = el.dataset[`roadsense${attr.replace(/[^a-z]/gi, "")}`];
      el.setAttribute(attr, translateText(original));
    });
  });
}
